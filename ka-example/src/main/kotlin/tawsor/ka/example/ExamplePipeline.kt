package tawsor.ka.example

import kotlinx.coroutines.runBlocking
import tawsor.ka.core.PipelineResult
import tawsor.ka.core.pipeline
import tawsor.ka.http.httpGet
import tawsor.ka.http.pollUntil
import tawsor.ka.tasks.FileSystem
import tawsor.ka.tasks.gitBranch
import tawsor.ka.tasks.gitCommit
import tawsor.ka.tasks.loadDotenv
import tawsor.ka.tasks.sh
import java.io.File
import kotlin.time.Duration.Companion.milliseconds
import kotlin.time.Duration.Companion.seconds

fun main() = runBlocking {
    println("--- Executing Sample Kotlin Automation Scenario ---")

    val fullPipeline = pipeline("Comprehensive Automation Suite") {

        step("1. Inspect Environment & VCS") {
            loadDotenv() // Loads .env if present
            val branch = gitBranch()
            val commit = gitCommit()
            logInfo("Running in Git branch: $branch, commit: $commit")
            set("branch_name", branch)
        }

        step("2. Workspace Filesystem Prep") {
            val tempDir = File("build/temp_automation")
            FileSystem.cleanDirectory(tempDir)
            File(tempDir, "sample.txt").writeText("Generated by Kotlin Automation")
            logSuccess("Prepared workspace directory: ${tempDir.absolutePath}")
            set("temp_dir", tempDir)
        }

        parallel("3. Run Parallel Health Checks") {
            step("Ping GitHub API") {
                val response = httpGet("https://api.github.com/zen")
                logInfo("GitHub Zen Quote: '$response'")
            }

            step("Local Shell Verification", retries = 1, retryDelay = 200.milliseconds) {
                val dirListing = sh("echo KA task verification")
                logInfo("Shell output: $dirListing")
            }
        }

        step("4. Simulated Health Polling") {
            var counter = 0
            pollUntil(timeout = 5.seconds, interval = 200.milliseconds, description = "Service Readiness") {
                counter++
                counter >= 3
            }
            logSuccess("Health polling resolved successfully after 3 ticks!")
        }

        onSuccess { ctx ->
            ctx.logSuccess("Pipeline completed! (Optional: send Telegram / Discord alerts here)")
        }

        onFailure { ctx, error ->
            ctx.logError("Pipeline failed with: ${error.message} (Optional: send alert here)")
        }
    }

    when (val result = fullPipeline.execute()) {
        is PipelineResult.Success -> {
            println("=== Scenario executed successfully in ${result.duration} ===")
        }
        is PipelineResult.Failure -> {
            System.err.println("=== Scenario failed at step ${result.failedStep}: ${result.cause.message} ===")
        }
    }
}
